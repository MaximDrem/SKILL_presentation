function textWidth(text, scale = 2) {
  return [...text].length * 6 * scale - scale;
}
function drawText(img, x, y, text, rgb, scale = 2) {
  let cx = x;
  for (const ch of text) {
    const glyph = FONT[ch] || FONT[ch.toLowerCase()] || FONT[' '];
    for (let col = 0; col < 5; col++) {
      const bits = glyph[col];
      for (let row = 0; row < 7; row++) {
        if (bits & (1 << row)) {
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + col * scale + sx, py = y + row * scale + sy;
              if (px >= 0 && py >= 0 && px < img.width && py < img.height) {
                const o = (py * img.width + px) * img.channels;
                img.data[o] = rgb[0]; img.data[o + 1] = rgb[1]; img.data[o + 2] = rgb[2];
                if (img.channels === 4) img.data[o + 3] = 255;
              }
            }
          }
        }
      }
    }
    cx += 6 * scale;
  }
}
